// Define transaction structure
export interface Transaction {
  id: string;
  date: string; // ISO date string (YYYY-MM-DD)
  time?: string; // HH:mm format (e.g. "14:35") — optional for backward compat
  type: 'income' | 'expense';
  category: string;
  amount: number;
  accountId: string;
  description: string;
  isRecurring: boolean;
  recurrenceRule?: 'weekly' | 'monthly' | 'yearly';
  tags?: string[];
  notes?: string;
  receiptImage?: string; // Phase 1.3: Base64 compressed receipt image
  isAutoGenerated?: boolean; // Phase 1.1: Auto-generated from recurring rule
}

// Define lending structure (loans given to/taken from others)
