import { db, generateUUID, syncAccountToAsset } from '@/db/schema'
import type { PlannedPayment } from '@/db/schema'
import { formatCurrency } from '@/lib/utils'
import type { PlannedPaymentDraft } from '@/components/modules/planned-payment-form'

const LAST_RUN_KEY = 'pennyflow-planned-last-run'
// Safety cap so a long-dormant recurring plan can't flood the ledger.
const MAX_BACKFILL = 366

/**
 * PlannedPaymentService
 * ----------------------
 * CRUD + lifecycle for Planned Payments (future cash flow). Creating/editing a
 * plan NEVER touches account balances — a planned payment is a projection. Only
 * when a plan is "marked done" (executed) do we create a real transaction and
 * move money, mirroring the quick-add write path.
 */
export class PlannedPaymentService {
  private static today(): string {
    return new Date().toISOString().split('T')[0]
  }

  /** Step a YYYY-MM-DD date forward by one recurrence interval. */
  private static advance(dateStr: string, rule: 'weekly' | 'monthly' | 'yearly'): string {
    const d = new Date(dateStr + 'T00:00:00')
    if (isNaN(d.getTime())) return dateStr
    switch (rule) {
      case 'weekly': d.setDate(d.getDate() + 7); break
      case 'monthly': d.setMonth(d.getMonth() + 1); break
      case 'yearly': d.setFullYear(d.getFullYear() + 1); break
    }
    return d.toISOString().split('T')[0]
  }

  /** Create a new planned payment from a form draft. */
  static async create(draft: PlannedPaymentDraft): Promise<string> {
    const id = generateUUID()
    const record: PlannedPayment = {
      id,
      type: draft.type,
      category: draft.category,
      amount: draft.amount,
      accountId: draft.accountId,
      date: draft.date,
      time: draft.time,
      description: draft.description || '',
      frequency: draft.frequency,
      recurrenceRule: draft.frequency === 'recurring' ? draft.recurrenceRule : undefined,
      tags: draft.tags,
      autoExecute: draft.autoExecute ?? true,
      status: 'planned',
      createdAt: new Date().toISOString(),
    }
    await db.transaction('rw', [db.plannedPayments, db.systemLogs], async () => {
      await db.plannedPayments.add(record)
      await db.systemLogs.add({
        id: generateUUID(),
        timestamp: new Date().toISOString(),
        type: 'system',
        description: `Planned ${draft.type}: ${draft.description || draft.category} (${formatCurrency(draft.amount)})`,
      } as any)
    })
    return id
  }

  /** Update an existing planned payment from a form draft. */
  static async update(id: string, draft: PlannedPaymentDraft): Promise<void> {
    await db.plannedPayments.update(id, {
      type: draft.type,
      category: draft.category,
      amount: draft.amount,
      accountId: draft.accountId,
      date: draft.date,
      time: draft.time,
      description: draft.description || '',
      frequency: draft.frequency,
      recurrenceRule: draft.frequency === 'recurring' ? draft.recurrenceRule : undefined,
      tags: draft.tags,
      autoExecute: draft.autoExecute ?? true,
    })
  }

  static async remove(id: string): Promise<void> {
    await db.plannedPayments.delete(id)
  }

  /** Cancel a plan without deleting it (keeps the history). */
  static async cancel(id: string): Promise<void> {
    await db.plannedPayments.update(id, { status: 'cancelled' })
  }

  /**
   * Execute a single occurrence of a plan on `occurrenceDate`: create a real
   * transaction, move money on the linked account, log it, and (when `notify`)
   * raise a notification. This is the shared core used by both manual
   * completion and the automatic due-date processor. It does NOT change the
   * plan's own date/status — the caller decides how to advance the plan.
   *
   * Runs inside the caller-provided Dexie transaction `tx`.
   */
  private static async executeOccurrence(
    plan: PlannedPayment,
    occurrenceDate: string,
    notify: boolean,
  ): Promise<string> {
    const txId = generateUUID()
    await db.transactions.add({
      id: txId,
      date: occurrenceDate,
      time: plan.time,
      type: plan.type,
      category: plan.category,
      amount: plan.amount,
      accountId: plan.accountId,
      description: plan.description,
      tags: plan.tags,
      isRecurring: false,
      isAutoGenerated: true,
    } as any)

    const account = await db.accounts.get(plan.accountId)
    if (account) {
      const delta = plan.type === 'expense' ? -plan.amount : plan.amount
      const newBalance = account.balance + delta
      await db.accounts.update(plan.accountId, { balance: newBalance })
      await syncAccountToAsset(account.name, newBalance)
    }

    await db.systemLogs.add({
      id: generateUUID(),
      timestamp: new Date().toISOString(),
      type: 'transaction',
      description: `Planned ${plan.type} executed: ${plan.description || plan.category} (${formatCurrency(plan.amount)})`,
      amount: plan.type === 'expense' ? -plan.amount : plan.amount,
    } as any)

    if (notify) {
      await db.notifications.add({
        id: generateUUID(),
        type: 'transaction',
        title: `Planned ${plan.type} logged`,
        message: `${plan.description || plan.category} (${plan.type === 'expense' ? '-' : '+'}${formatCurrency(plan.amount)}) was auto-logged.`,
        read: false,
        timestamp: new Date().toISOString(),
      } as any)
    }

    return txId
  }

  /**
   * Execute a planned payment now (manual "Mark done"): logs the occurrence on
   * today's date, then rolls a recurring plan to its next date or completes a
   * one-time plan.
   */
  static async markDone(id: string): Promise<void> {
    const plan = await db.plannedPayments.get(id)
    if (!plan || plan.status !== 'planned') return

    await db.transaction('rw', [db.plannedPayments, db.transactions, db.accounts, db.assets, db.systemLogs, db.notifications], async () => {
      const txId = await this.executeOccurrence(plan, this.today(), false)

      if (plan.frequency === 'recurring' && plan.recurrenceRule) {
        const nextDate = this.advance(plan.date, plan.recurrenceRule)
        await db.plannedPayments.update(id, { date: nextDate, lastTransactionId: txId })
      } else {
        await db.plannedPayments.update(id, {
          status: 'completed',
          completedAt: new Date().toISOString(),
          lastTransactionId: txId,
        })
      }
    })
  }

  /* ---------------- Automatic due-date processing ---------------- */

  private static hasRunToday(): boolean {
    if (typeof window === 'undefined') return true
    return localStorage.getItem(LAST_RUN_KEY) === this.today()
  }

  private static markAsRun(): void {
    if (typeof window === 'undefined') return
    localStorage.setItem(LAST_RUN_KEY, this.today())
  }

  /**
   * App-load engine. Finds every auto-executing planned payment that is due
   * (date <= today) and logs it:
   *   • one-time  → execute once on its date, then mark completed.
   *   • recurring → execute each missed occurrence from its date up to today
   *                 (capped), then roll the plan forward to the next future date.
   *
   * Idempotent per day via a localStorage last-run key, and safe to run
   * repeatedly: each pass only acts on occurrences still due. Returns the number
   * of transactions created.
   */
  static async processDue(): Promise<number> {
    if (this.hasRunToday()) return 0

    const today = this.today()
    const all = await db.plannedPayments.toArray()
    const due = all.filter(
      p => p.status === 'planned' && (p.autoExecute ?? true) && p.date <= today,
    )

    let created = 0

    for (const plan of due) {
      await db.transaction('rw', [db.plannedPayments, db.transactions, db.accounts, db.assets, db.systemLogs, db.notifications], async () => {
        // Re-read inside the txn to avoid acting on stale state.
        const fresh = await db.plannedPayments.get(plan.id)
        if (!fresh || fresh.status !== 'planned') return

        if (fresh.frequency === 'recurring' && fresh.recurrenceRule) {
          let cursor = fresh.date
          let lastTxId: string | undefined
          let guard = 0
          // Log every occurrence from the plan's date up to and including today.
          while (cursor <= today && guard < MAX_BACKFILL) {
            lastTxId = await this.executeOccurrence(fresh, cursor, true)
            created++
            cursor = this.advance(cursor, fresh.recurrenceRule)
            guard++
          }
          // `cursor` now points at the next future occurrence.
          await db.plannedPayments.update(fresh.id, { date: cursor, lastTransactionId: lastTxId })
        } else {
          const txId = await this.executeOccurrence(fresh, fresh.date, true)
          created++
          await db.plannedPayments.update(fresh.id, {
            status: 'completed',
            completedAt: new Date().toISOString(),
            lastTransactionId: txId,
          })
        }
      })
    }

    this.markAsRun()
    return created
  }
}
